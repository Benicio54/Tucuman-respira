comment on column public.mediciones.id is
  'Identificador interno autoincremental.';
comment on column public.mediciones.created_at is
  'Fecha y hora UTC de la lectura (por defecto now()).';
comment on column public.mediciones.co2 is
  'CO₂ en ppm medido por el MH-Z19C.';
comment on column public.mediciones.co is
  'CO en ppm calculado con la curva MQ-7 corregida (100 · (Rs/R0)^-1.513).';
comment on column public.mediciones.pm1 is
  'PM1.0 atmosférico del PMS5003 en µg/m³ (informativo, no entra al ICA).';
comment on column public.mediciones.pm25 is
  'PM2.5 atmosférico del PMS5003 en µg/m³ (entra al ICA EPA).';
comment on column public.mediciones.pm10 is
  'PM10 atmosférico del PMS5003 en µg/m³ (entra al ICA EPA).';
