-- ============================================================
-- Tucumán Respira · Base de datos completa
-- ============================================================
-- Script único e idempotente. Crea TODA la base de datos desde
-- cero si hace falta y, si ya existe, la completa sin duplicar
-- datos ni sobrescribir el backfill.
--
-- Ejecutar completo en Supabase → SQL Editor → Run.
--
-- Contenido:
--   PARTE 0 · Preparación (esquema y extensiones)
--   PARTE 1 · Tabla mediciones (creación desde cero + columnas)
--   PARTE 2 · Índices
--   PARTE 3 · Seguridad: RLS, políticas y permisos
--   PARTE 4 · Realtime (opcional pero recomendado)
--   PARTE 5 · Vista ica_promedios (promedios 24 h / 8 h)
--   PARTE 6 · Backfill histórico
--   PARTE 7 · Verificación
--
-- Modelo de acceso:
--   · El ESP32 escribe con la clave publicable (rol anon) → INSERT.
--   · El panel web lee con la clave publicable (rol anon) → SELECT.
--   · No se exponen UPDATE ni DELETE al rol anon.
-- ============================================================


-- ============================================================
-- PARTE 0 · PREPARACIÓN
-- ============================================================

create schema if not exists public;

-- gen_random_uuid() por si se usa en el futuro; en Supabase ya
-- suele estar instalada. No es imprescindible para este esquema.
create extension if not exists pgcrypto;


-- ============================================================
-- PARTE 1 · TABLA MEDICIONES
-- ============================================================
-- Una fila por lectura del dispositivo. El ESP32 publica cada
-- 15 s; los promedios del ICA se calculan en la vista.

create table if not exists public.mediciones (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  co2              integer,
  co               double precision,
  pm1              integer,
  pm25             integer,
  pm10             integer,
  temperatura      double precision,
  humedad          integer,
  presion          integer,
  uv               double precision,
  luz              integer,
  latitud          double precision,
  longitud         double precision,
  ip_dispositivo   text
);

-- Compatibilidad con bases creadas por versiones anteriores:
-- agrega cualquier columna faltante sin tocar las existentes.
alter table public.mediciones add column if not exists created_at     timestamptz not null default now();
alter table public.mediciones add column if not exists co2            integer;
alter table public.mediciones add column if not exists co             double precision;
alter table public.mediciones add column if not exists pm1            integer;
alter table public.mediciones add column if not exists pm25           integer;
alter table public.mediciones add column if not exists pm10           integer;
alter table public.mediciones add column if not exists temperatura    double precision;
alter table public.mediciones add column if not exists humedad        integer;
alter table public.mediciones add column if not exists presion        integer;
alter table public.mediciones add column if not exists uv             double precision;
alter table public.mediciones add column if not exists luz            integer;
alter table public.mediciones add column if not exists latitud        double precision;
alter table public.mediciones add column if not exists longitud       double precision;
alter table public.mediciones add column if not exists ip_dispositivo text;

-- La fecha debe generarse sola si el dispositivo no la envía.
alter table public.mediciones alter column created_at set default now();

comment on table public.mediciones is
