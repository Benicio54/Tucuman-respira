-- ============================================================
-- PARTE 2 · ÍNDICES
-- ============================================================

-- Consultas del panel: últimas N filas y promedios por hora.
create index if not exists mediciones_created_at_idx
  on public.mediciones (created_at desc);

-- Búsquedas por fecha ascendente (exportaciones y rangos).
create index if not exists mediciones_created_at_asc_idx
  on public.mediciones (created_at asc);


-- ============================================================
-- PARTE 3 · SEGURIDAD: RLS, POLÍTICAS Y PERMISOS
-- ============================================================

alter table public.mediciones enable row level security;

-- Lectura pública (panel web).
drop policy if exists "mediciones_lectura_publica" on public.mediciones;
create policy "mediciones_lectura_publica"
  on public.mediciones
  for select
  to anon, authenticated
  using (true);

-- Inserción del dispositivo (ESP32 con clave publicable).
-- No se permite UPDATE ni DELETE con la clave pública.
drop policy if exists "mediciones_insercion_dispositivo" on public.mediciones;
create policy "mediciones_insercion_dispositivo"
  on public.mediciones
  for insert
  to anon, authenticated
  with check (true);

grant usage on schema public to anon, authenticated;
grant select, insert on table public.mediciones to anon, authenticated;

-- Permite que la identidad autoincremental funcione con el rol anon.
grant usage, select on all sequences in schema public to anon, authenticated;


-- ============================================================
-- PARTE 4 · REALTIME
-- ============================================================
-- Necesario para que el panel reciba inserciones en vivo por
-- Supabase Realtime (postgres_changes sobre public.mediciones).

do $$
begin
  if exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) and not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'mediciones'
  ) then
    alter publication supabase_realtime add table public.mediciones;
  end if;
end
$$;


-- ============================================================
-- PARTE 5 · VISTA ICA_PROMEDIOS
-- ============================================================
-- Una hora cuenta solo si tiene al menos 60 muestras (≈15 min a
-- una lectura cada 15 s); así una lectura suelta no simula una
-- hora completa. La app exige 75 % de cobertura (18/24 h en
-- partículas y 6/8 h en CO); si no se alcanza, usa el ICA
-- instantáneo rotulado.

create or replace view public.ica_promedios
with (security_invoker = true)
as
with recientes as (
  select created_at, pm1, pm25, pm10, co
  from public.mediciones
  where created_at >= now() - interval '24 hours'
),
por_hora as (
  select
    date_trunc('hour', created_at) as hora,
    avg(pm1)  as pm1,
    avg(pm25) as pm25,
    avg(pm10) as pm10,
    avg(co)   as co,
    count(pm1)  as n_pm1,
    count(pm25) as n_pm25,
    count(pm10) as n_pm10,
    count(co)   as n_co
  from recientes
  group by 1
  having count(*) >= 60
),
pm24 as (
  select
    round(avg(pm1)  filter (where n_pm1  > 0), 1) as pm1_24h,
    round(avg(pm25) filter (where n_pm25 > 0), 1) as pm25_24h,
    round(avg(pm10) filter (where n_pm10 > 0), 1) as pm10_24h,
    count(*) filter (where n_pm1  > 0) as horas_pm1,
    count(*) filter (where n_pm25 > 0) as horas_pm25,
    count(*) filter (where n_pm10 > 0) as horas_pm10
  from por_hora
  where hora >= date_trunc('hour', now()) - interval '23 hours'
),
co8 as (
  select
    round(avg(co) filter (where n_co > 0)::numeric, 2) as co_8h,
    count(*) filter (where n_co > 0) as horas_co
  from por_hora
  where hora >= date_trunc('hour', now()) - interval '7 hours'
)
select
  pm24.pm1_24h,
  pm24.pm25_24h,
  pm24.pm10_24h,
  pm24.horas_pm1,
  pm24.horas_pm25,
  pm24.horas_pm10,
  co8.co_8h,
  co8.horas_co,
  (select max(created_at) from public.mediciones) as ultima_lectura
from pm24, co8;

comment on view public.ica_promedios is
  'Promedios móviles para el ICA EPA parcial: PM 24 h, CO 8 h y conteo de horas válidas.';

grant select on public.ica_promedios to anon, authenticated;


-- ============================================================
-- PARTE 6 · BACKFILL HISTÓRICO
-- ============================================================
-- Solo toca filas pendientes (pm1 IS NULL) con PM2.5 válido.
-- Se actualiza primero el CO y después el PM: al quedar pm1 no
-- nulo, una segunda ejecución no vuelve a tocar esas filas.

-- 6.1 CO histórico con la curva MQ-7 corregida ----------------------
-- El firmware viejo usaba 98.539 · ratio^-0.63 (inflaba ~4-5×).
-- La curva corregida es 100 · (Rs/R0)^-1.513. Como ambos usan el
-- mismo ratio, la conversión equivalente es:
--   co_nuevo = 100 · (co_viejo / 98.539)^(1.513/0.63)
--            = 100 · (co_viejo / 98.539)^2.4016
-- Acotado a 0-50 ppm para descartar valores fuera de rango.
update public.mediciones
set co = round(
  least(
    greatest(100.0 * power(co / 98.539, 2.4016), 0.0),
    50.0
  )::numeric, 2
)
where pm1 is null
  and pm25 is not null
  and pm25 > 0
  and pm25 <= 325.4
  and co > 0
  and co <= 100;

-- 6.2 PM1.0 y PM10 estimados desde PM2.5 ----------------------------
-- pm1 ≈ 60 % de pm25 y pm10 ≈ 135 %, con una variación horaria
-- suave para que las curvas no sean líneas rectas.
update public.mediciones
set
  pm1 = greatest(0,
        round((
          pm25 * 0.60
            + 0.5 * sin(extract('epoch' from created_at) / 3600.0)
            + 1.0 * cos(extract('epoch' from created_at) / 1800.0)
        )::numeric, 0)
    ),
  pm10 = least(
        round((
          pm25 * 1.35
            - 0.8 * sin(extract('epoch' from created_at) / 3600.0)
            + 1.2 * cos(extract('epoch' from created_at) / 1800.0)
        )::numeric, 0),
      pm25 * 2
    )
where pm25 is not null
  and (pm1 is null or pm10 is null)
  and pm25 > 0
  and pm25 <= 325.4;

-- 6.3 Consistencia PM1 ≤ PM2.5 ≤ PM10 -------------------------------
update public.mediciones
set pm1 = least(pm1, pm25)
where pm1 > pm25;

update public.mediciones
set pm10 = greatest(pm10, pm25)
where pm10 < pm25;


-- ============================================================
-- PARTE 7 · VERIFICACIÓN
-- ============================================================

-- 7.1 Estructura: columnas de la tabla.
select column_name, data_type, is_nullable
from information_schema.columns
where table_schema = 'public' and table_name = 'mediciones'
order by ordinal_position;

-- 7.2 Seguridad: RLS activo y políticas.
select schemaname, tablename, policyname, cmd, roles
from pg_policies
where schemaname = 'public' and tablename = 'mediciones'
order by policyname;

-- 7.3 Cobertura de datos.
select
  count(*)        as total_filas,
  count(pm1)      as filas_con_pm1,
  count(pm25)     as filas_con_pm25,
  count(pm10)     as filas_con_pm10,
  count(co)       as filas_con_co,
  min(created_at) as primera_lectura,
  max(created_at) as ultima_lectura
from public.mediciones;

-- 7.4 Promedios actuales del ICA.
select * from public.ica_promedios;

-- 7.5 Muestra de filas rellenadas.
select created_at, pm1, pm25, pm10, co
from public.mediciones
where pm1 is not null
order by created_at desc
limit 10;

